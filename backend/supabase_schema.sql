    recorded_at timestamp with time zone not null default timezone('utc'::text, now()),
    mood integer,
    energy integer,
    stress integer,
    sleep_hours double precision,
    pain_level integer,
    blood_glucose_mg_dl double precision,
    hydration_ml integer,
    nutrition_quality text,
