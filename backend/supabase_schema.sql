create table if not exists public.telemetry_logs (
    id bigint generated by default as identity primary key,
    astronaut_id text references public.astronauts(id) on delete cascade,
    timestamp timestamp with time zone default timezone('utc'::text, now()),
    heart_rate double precision not null,
    spo2 double precision not null,
    core_temp double precision not null,
    radiation_rate double precision not null,
    hrv double precision not null,
    systolic_bp double precision default 120.0,
    diastolic_bp double precision default 80.0,
    respiration_rate double precision default 14.0,
    battery_level double precision default 98.0,
    telemetry_source text not null default 'simulated',
    orbital_phase text,
    calibration_basis text,
    is_synced boolean default true,
    blood_glucose double precision,
    wbc_k_ul double precision,
    hydration_pct double precision,
    mission_zone text,
    mission_day integer,
    distance_km double precision,
    comms_latency_sec double precision,
    gravity_g double precision,
    shielding_mode text,
    cumulative_dose_msv double precision,
    overall_health_score double precision,
    health_status text,
    iss_latitude double precision,
    iss_longitude double precision,
    iss_altitude_km double precision
);

create index if not exists idx_telemetry_astro_time on public.telemetry_logs(astronaut_id, timestamp desc);

create table if not exists public.alerts (
    id text primary key default gen_random_uuid()::text,
    astronaut_id text references public.astronauts(id) on delete cascade,
    timestamp timestamp with time zone default timezone('utc'::text, now()),
    severity text not null,
    alert_type text not null,
    message text not null,
    acknowledged boolean default false,
    trigger_metric text,
    recommended_action text,
    hazard_domain text
);

create index if not exists idx_alerts_astro_time on public.alerts(astronaut_id, timestamp desc);

create table if not exists public.space_weather_events (
    event_id text primary key,
    event_type text not null,
    event_time timestamp with time zone not null,
    severity text not null default 'QUIET',
    summary text not null,
    kp_index double precision,
    flare_class text,
    source_location text,
    active_region_num integer,
    cme_speed_kms double precision,
    cme_half_angle double precision,
    cme_longitude double precision,
    cme_latitude double precision,
    earth_impact_eta timestamp with time zone,
    payload jsonb not null default '{}'::jsonb,
    source_url text,
    updated_at timestamp with time zone not null default timezone('utc'::text, now())
);

create index if not exists idx_space_weather_events_time on public.space_weather_events(event_time desc);
create index if not exists idx_space_weather_events_type_time on public.space_weather_events(event_type, event_time desc);

create table if not exists public.space_weather_status (
    id text primary key,
    kp_current double precision not null default 0.0,
    storm_level text not null default 'G0_QUIET',
    radiation_storm text not null default 'S0_NONE',
    latest_flare_class text,
    latest_flare_location text,
    latest_flare_time timestamp with time zone,
    active_sep boolean not null default false,
    earth_impact_eta timestamp with time zone,
    summary text not null default 'Awaiting initial NASA DONKI sync.',
    source_mode text not null default 'historical_fallback',
    fetched_at timestamp with time zone not null default timezone('utc'::text, now()),
    payload jsonb not null default '{}'::jsonb
);

