
-- NASA Space Apps Challenge - Biotelemetry Health Monitoring Space
-- Supabase PostgreSQL Database Schema

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- 1. ASTRONAUTS TABLE
create table if not exists public.astronauts (
    id text primary key,
    name text not null,
    role text not null,
    age integer not null default 35,
    resting_hr double precision not null default 60.0,
    baseline_spo2 double precision not null default 98.5,
    status text not null default 'NOMINAL',
    suit_id text default 'EMU-X1',
    created_at timestamp with time zone default timezone('utc'::text, now())
);

