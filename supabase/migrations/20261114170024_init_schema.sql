-- 2. TELEMETRY LOGS (Historical time-series vitals)
create table if not exists public.telemetry_logs (
    id bigint generated by default as identity primary key,
    astronaut_id text references public.astronauts(id) on delete cascade,
    timestamp timestamp with time zone default timezone('utc'::text, now()),
    heart_rate double precision not null,
    spo2 double precision not null,
    core_temp double precision not null,
    radiation_rate double precision not null,
    hrv double precision not null,
    is_synced boolean default true
);

-- Index for fast time-series queries
create index if not exists idx_telemetry_astro_time on public.telemetry_logs(astronaut_id, timestamp desc);

-- 3. ALERTS TABLE (Medical alerts & triage)
create table if not exists public.alerts (
    id text primary key default gen_random_uuid()::text,
    astronaut_id text references public.astronauts(id) on delete cascade,
    timestamp timestamp with time zone default timezone('utc'::text, now()),
    severity text not null, -- 'INFO', 'WARNING', 'CRITICAL'
    alert_type text not null, -- 'HYPOXIA', 'TACHYCARDIA', 'BRADYCARDIA', 'RADIATION_SPIKE'
    message text not null,
    acknowledged boolean default false
);

-- Enable Supabase Realtime for instant front-end push
alter publication supabase_realtime add table public.telemetry_logs;
alter publication supabase_realtime add table public.alerts;

-- Disable Row Level Security (RLS) for public hackathon demo mode or enable with open policies
alter table public.astronauts enable row level security;
alter table public.telemetry_logs enable row level security;
alter table public.alerts enable row level security;

create policy "Public read astronauts" on public.astronauts for select using (true);
create policy "Public write astronauts" on public.astronauts for all using (true);

create policy "Public read telemetry" on public.telemetry_logs for select using (true);
create policy "Public insert telemetry" on public.telemetry_logs for insert with check (true);

create policy "Public read alerts" on public.alerts for select using (true);
create policy "Public write alerts" on public.alerts for all using (true);

